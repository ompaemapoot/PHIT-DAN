// Test the actual leaderboard code with isolated localStorage and a minimal DOM.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync(require('node:path').join(__dirname, '../game.js'), 'utf8');
const code = source.slice(source.indexOf('const $ ='), source.indexOf('let playing ='));
const storage = new Map([['phit-dan-leaderboard-v2', JSON.stringify([[7, 1]])]]);
function makeContext() {
  function element() { return {value:'', textContent:'', hidden:false, attributes:{}, children:[], classList:{add(){},remove(){}}, setAttribute(name,value){this.attributes[name]=value;}, removeAttribute(name){delete this.attributes[name];}, appendChild(child){this.children.push(child);}, append(...children){this.children.push(...children);}, replaceChildren(){this.children=[];}, addEventListener(type,fn){this[type]=fn;}, focus(){}}; }
  const elements = new Proxy({}, {get:(target,id)=>target[id] ||= element()});
  const context=vm.createContext({document:{documentElement:{dataset:{}},getElementById:id=>elements[id],createElement:element},localStorage:{getItem:key=>storage.get(key) ?? null,setItem:(key,value)=>storage.set(key,value)}});
  vm.runInContext(code,context);
  return {context,elements};
}
// Each row now leads with a rank badge, so the player name is the second child.
const nameAt=(elements,index=0)=>elements['leaderboard-list'].children[index].children[1].textContent;
const first=makeContext();
assert.match(source,/badge\.classList\.add\('royal'\)/,'top three rows should render a crown badge');
assert.match(source,/class="crown" d="M3\.6 19\.6V8\.6/,'the crown badge should draw the crown crest');
assert.match(require('node:fs').readFileSync(require('node:path').join(__dirname,'../style.css'),'utf8'),/\.leaderboard li\.top-1\{--medal:var\(--gold\)\}/,'rank one should be gold');
assert.match(first.elements['leaderboard-mode'].textContent,/Hub/);
assert.equal(nameAt(first.elements),'Unknown');
first.elements['leaderboard-toggle'].click();
assert.equal(first.elements['leaderboard-modes'].hidden,false);
assert.equal(first.elements['mode-field'].hidden,true);
first.elements['scores-horizontal'].click();
assert.match(first.elements['leaderboard-mode'].textContent,/Rail/);
assert.equal(first.elements['scores-horizontal'].attributes['aria-pressed'],'true');
assert.equal(first.elements['scores-arcade'].attributes['aria-pressed'],'false');
assert.equal(first.elements['leaderboard-empty'].hidden,false);
vm.runInContext("playerName='Horizontal player'; saveScore(12)",first.context);
assert.equal(JSON.parse(storage.get('phit-dan-leaderboard-horizontal-v1'))[0][0],12);
assert.equal(storage.has('phit-dan-leaderboard-v3'),false);
first.elements['scores-arcade'].click();
assert.equal(nameAt(first.elements),'Unknown');
vm.runInContext("playerName='Arcade player'; saveScore(3)",first.context);
assert.equal(JSON.parse(storage.get('phit-dan-leaderboard-v3')).length,2);
first.elements['scores-timing'].click();
assert.match(first.elements['leaderboard-mode'].textContent,/Beat/);
assert.equal(first.elements['scores-timing'].attributes['aria-pressed'],'true');
assert.equal(first.elements['scores-arcade'].attributes['aria-pressed'],'false');
vm.runInContext("playerName='Timing player'; saveScore(22)",first.context);
assert.deepEqual(JSON.parse(storage.get('phit-dan-leaderboard-timing-v1'))[0],[22,'Timing player',1]);
assert.equal(storage.get('phit-dan-leaderboard-horizontal-v1'),JSON.stringify([[12,'Horizontal player',1]]),
  'Timing scores must not share storage with Rush');
const reload=makeContext();
reload.elements['scores-horizontal'].click();
assert.equal(nameAt(reload.elements),'Horizontal player');
reload.elements['scores-arcade'].click();
assert.equal(nameAt(reload.elements),'Unknown');
reload.elements['scores-timing'].click();
assert.equal(nameAt(reload.elements),'Timing player');
first.elements['leaderboard-back'].click();
assert.equal(first.elements['leaderboard-modes'].hidden,true);
assert.equal(first.elements['mode-field'].hidden,true,'back returns to the collapsed menu with the Play button');
assert.equal(first.elements['play-btn'].hidden,false);
first.elements['player-name'].value='Test player';
first.elements['play-btn'].click();
assert.equal(first.elements['mode-field'].hidden,false,'Play reveals the mode choices');
assert.equal(first.elements['player-field'].hidden,true,'the mode view should not repeat the name field');
assert.equal(first.elements['play-btn'].hidden,true);
assert.equal(first.elements['leaderboard-toggle'].hidden,true,'the mode view hides Leaderboard');
assert.equal(first.elements['settings-menu'].hidden,true,'the mode view hides Settings');
first.elements['leaderboard-toggle'].click();
assert.equal(first.elements['mode-field'].hidden,true);
first.elements['leaderboard-back'].click();
assert.equal(first.elements['mode-field'].hidden,false,'back keeps the mode choices open when they were open');
first.elements['mode-back'].click();
assert.equal(first.elements['mode-field'].hidden,true,'Back collapses the mode choices');
assert.equal(first.elements['play-btn'].hidden,false);
assert.equal(first.elements['player-field'].hidden,false,'Back restores the name field');
assert.equal(first.elements['leaderboard-toggle'].hidden,false,'Back restores Leaderboard');
assert.equal(first.elements['settings-menu'].hidden,false,'Back restores Settings');
first.elements['player-name-error'].hidden=true;
first.elements['player-name'].value='';
first.elements['play-btn'].click();
assert.equal(first.elements['mode-field'].hidden,true,'Play should refuse an empty name');
assert.equal(first.elements['player-name-error'].hidden,false,'the missing name should be reported on the first screen');
assert.equal(first.elements['play-btn'].hidden,false);
console.log('Mode leaderboard isolation checks passed.');
